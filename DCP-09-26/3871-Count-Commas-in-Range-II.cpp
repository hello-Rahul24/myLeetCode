class Solution {
public:
    long long countCommas(long long n) {
        if(n < 1000) return 0;
        long long ans = 0;
        if(1000 <= n && n <= 999999){
            return n - 999;
        }
        if(1000000 <= n && n <= 999999999){
            return (n - 999999)*2 + (999999-999);
        }
        if(1000000000 <= n && n <= 999999999999){
            return (n - 999999999)*3 + (999999999 - 999999)*2 + (999999-999);
        }
        if(1000000000000 <= n && n <= 999999999999999){
            return (n - 999999999999)*4 + (999999999999 -999999999)*3 +(999999999 - 999999)*2 + (999999-999);
        }
        if(1000000000000000 <= n && n <= 999999999999999999){
            return (n- 999999999999999)*5 + (999999999999999 - 999999999999)*4 + (999999999999 -999999999)*3 +(999999999 - 999999)*2 + (999999-999);
        }
        return 0;
    }
};